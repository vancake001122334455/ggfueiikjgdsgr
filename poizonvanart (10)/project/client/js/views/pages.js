export async function renderPage(route) {
  const slug = route.params[0];
  const wrap = h('div', { class: 'container', style: { maxWidth: '960px' } });
  const map = {
    how: pageHow, guarantee: pageGuarantee, reviews: pageReviews,
    offer: () => legal('Публичная оферта', OFFER), privacy: () => legal('Политика конфиденциальности', PRIVACY),
    terms: () => legal('Пользовательское соглашение', OFFER), refund: () => legal('Правила возврата', REFUND),
    requisites: () => legal('Реквизиты', REQUISITES), contacts: pageContacts,
    404: () => h('div', { class: 'card center' }, h('h1', {}, '404'), h('p', { class: 'muted' }, 'Страница не найдена'), h('a', { class: 'btn btn-primary', href: '#/' }, 'На главную')),
  };
  const fn = map[slug] || map[404];
  wrap.appendChild(await fn());
  return wrap;
}

