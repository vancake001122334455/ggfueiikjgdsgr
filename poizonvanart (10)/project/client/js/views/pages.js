// ── ОТЗЫВЫ ─────────────────────────────────────────────────────────────────
async function pageReviews() {
  const wrap = h('div', {}, pageHead('Отзывы и фото выкупленных товаров', 'Реальные заказы клиентов PoizonVanart: фотоотчёты со склада, сроки и впечатления.'));
  const box = h('div', { class: 'grid grid-2' }, h('div', { class: 'skeleton', style: { height: '120px' } }));
  wrap.appendChild(box);
  try {
    const reviews = await endpoints.reviews();
    box.innerHTML = '';
    reviews.forEach((r) => box.appendChild(h('div', { class: 'card' },
      h('div', { class: 'row gap-3', style: { marginBottom: '10px' } },
        h('span', { class: 'avatar' }, (r.author_name || 'К')[0]),
        h('div', { class: 'grow' }, h('b', { class: 'small' }, r.author_name),
          h('div', { class: 'tiny', style: { color: 'var(--gold)' } }, '★'.repeat(r.rating || 5))),
        h('span', { class: 'chip chip-ok' }, 'проверенный заказ')),
      h('p', { class: 'small muted', style: { margin: 0 } }, r.body))));
  } catch (e) { box.textContent = e.message; }

  // фотоотчёты
  if (state.user) {
    try {
      const orders = await endpoints.orders();
      const withPhotos = orders.filter((o) => ['photo_report', 'packed', 'sent_to_ru', 'in_transit', 'delivered'].includes(o.status));
      if (withPhotos.length) {
        wrap.appendChild(h('h2', { style: { margin: '32px 0 14px' } }, 'Фотоотчёты по вашим заказам'));
        for (const o of withPhotos.slice(0, 3)) {
          const full = await endpoints.order(o.id);
          if (!full.photos?.length) continue;
          wrap.appendChild(h('div', { class: 'card', style: { marginBottom: '14px' } },
            h('div', { class: 'card-head' }, icon('camera', 18), h('b', { class: 'mono small' }, o.orderNo), h('span', { class: 'chip', style: { marginLeft: 'auto' } }, o.statusRu)),
            h('div', { class: 'gallery' }, full.photos.map((p) => h('figure', {}, h('img', { src: p.url, alt: p.caption || '', loading: 'lazy' }), h('figcaption', {}, p.caption || ''))))));
        }
      }
    } catch { /* noop */ }
  } else {
    wrap.appendChild(h('div', { class: 'notice notice-info', style: { marginTop: '24px' } }, icon('lock', 16),
      h('div', { class: 'small' }, 'Ваши персональные фотоотчёты со склада доступны после входа в кабинет.')));
  }
  return wrap;
}

